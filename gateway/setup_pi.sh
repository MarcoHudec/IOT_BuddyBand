#!/usr/bin/env bash
# BuddyBand gateway setup for the Raspberry Pi (WP3). Idempotent – safe to run again.
#
#   scp -r gateway buddyband-gw:~/buddyband-gateway
#   ssh -t buddyband-gw 'sudo bash ~/buddyband-gateway/setup_pi.sh'
#
# Installs RabbitMQ with MQTT (1883), web MQTT (15675) and management UI (15672),
# creates one user per client with a random password (architecture.md D12) and
# writes the passwords to ~<user>/buddyband-credentials.env (mode 600, never commit).
# The Pi login password is NOT touched (course rule).
set -euo pipefail

if [[ $EUID -ne 0 ]]; then echo "run with sudo"; exit 1; fi
OWNER="${SUDO_USER:-iotlabpi47}"
HOME_DIR="$(getent passwd "$OWNER" | cut -d: -f6)"
CRED="$HOME_DIR/buddyband-credentials.env"
HERE="$(cd "$(dirname "$0")" && pwd)"

echo "== 1/5 packages"
apt-get update -qq
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
  rabbitmq-server mosquitto-clients python3-pika python3-paho-mqtt >/dev/null
echo "   rabbitmq-server $(dpkg-query -W -f='${Version}' rabbitmq-server)"

echo "== 2/5 configuration"
install -m 644 "$HERE/rabbitmq/rabbitmq.conf" /etc/rabbitmq/rabbitmq.conf
rm -f /etc/rabbitmq/rabbitmq.config   # old Erlang-term format from the course template
rabbitmq-plugins enable --quiet rabbitmq_management rabbitmq_mqtt rabbitmq_web_mqtt >/dev/null
systemctl enable --quiet rabbitmq-server
systemctl restart rabbitmq-server
rabbitmqctl await_startup >/dev/null

echo "== 3/5 users"
# keep existing passwords on re-run
[[ -f "$CRED" ]] && source "$CRED"
gen() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c 20; }
declare -A PW=(
  [admin]="${BB_ADMIN_PW:-$(gen)}"
  [teacher-band]="${BB_TEACHER_PW:-$(gen)}"
  [nodered]="${BB_NODERED_PW:-$(gen)}"
  [logger]="${BB_LOGGER_PW:-$(gen)}"
  [forwarder]="${BB_FORWARDER_PW:-$(gen)}"
)
for u in "${!PW[@]}"; do
  if rabbitmqctl list_users --quiet | awk '{print $1}' | grep -qx "$u"; then
    rabbitmqctl change_password "$u" "${PW[$u]}" >/dev/null
  else
    rabbitmqctl add_user "$u" "${PW[$u]}" >/dev/null
  fi
  # MQTT/AMQP clients need configure/write/read on their own queues; routing is limited by topic permissions
  rabbitmqctl set_permissions -p / "$u" ".*" ".*" ".*" >/dev/null
done
rabbitmqctl set_user_tags admin administrator >/dev/null
rabbitmqctl set_user_tags nodered management >/dev/null
# teacher band: may publish only buddyband.*, read only its command topics
rabbitmqctl set_topic_permissions -p / teacher-band amq.topic '^buddyband\..*' '^buddyband\.[0-9]+\.cmd\..*' >/dev/null
# guest stays localhost-only (RabbitMQ default); remove it from the network anyway
rabbitmqctl delete_user guest >/dev/null 2>&1 || true

cat > "$CRED" <<EOF
# BuddyBand RabbitMQ credentials – generated by setup_pi.sh, DO NOT COMMIT
BB_ADMIN_PW=${PW[admin]}
BB_TEACHER_PW=${PW[teacher-band]}
BB_NODERED_PW=${PW[nodered]}
BB_LOGGER_PW=${PW[logger]}
BB_FORWARDER_PW=${PW[forwarder]}
EOF
chown "$OWNER": "$CRED"
chmod 600 "$CRED"

echo "== 4/5 self-test (MQTT publish -> subscribe on localhost)"
timeout 5 mosquitto_sub -h localhost -u nodered -P "${PW[nodered]}" -t 'buddyband/#' -C 1 -v > /tmp/bb_selftest &
sleep 1
mosquitto_pub -h localhost -u teacher-band -P "${PW[teacher-band]}" -t buddyband/1/selftest -m '{"ok":true}'
wait || true
if grep -q selftest /tmp/bb_selftest; then echo "   OK: $(cat /tmp/bb_selftest)"; else echo "   FAILED"; fi

echo "== 5/5 done"
IP=$(hostname -I | awk '{print $1}')
echo "   MQTT          mqtt://$(hostname).local:1883   ($IP)"
echo "   MQTT over WS  ws://$(hostname).local:15675/ws"
echo "   Management    http://$(hostname).local:15672   (user admin)"
echo "   Credentials   $CRED"
